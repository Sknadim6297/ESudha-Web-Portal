							<p style="text-align:justify;">The Ministry of Health and Family Welfare (MoHFW) launched eSudha – the National Telemedicine Service of India to address critical gaps in India’s healthcare system. This transformative platform aims to tackle:
</p>
<p><b>Shortage of Medicine Shop:</b> Many regions lack access to quality Medicine Shop and limiting healthcare availability for millions.</p>
<p><b>Overburdened District and Tertiary Hospitals:</b> Due to limited services at the primary healthcare level, higher-level hospitals face overwhelming demand, impacting their ability to provide timely, specialized care.</p>
<p><b>Absence of Health Record Creation at Primary and Secondary Levels:</b> A reliable system for maintaining health records at primary and secondary facilities is crucial for effective and coordinated care.
</p>


<p style="text-align:justify;">

Through eSudha, MoHFW is committed to overcoming these challenges by bringing quality healthcare to the doorstep of every Indian, ensuring easy, equitable, and timely access to medical consultations.
eSudha – National Telemedicine Service quickly evolved into the world’s largest documented telemedicine implementation in the primary healthcare. The National Telemedicine Service of India has already served more than 342,998,140 patients at over 131,152 Ayushman Arogya Mandirs (earlier called Health & Wellness Centers) as spokes through 16,957+ hubs (set up at secondary/tertiary level health facilities and medical colleges etc.) and more than 692 online OPDs serviced by a team of over 231,250 doctors, medical specialists, super-specialists and health workers as telemedicine practitioners [as on 05 February 2025].</p>
<p style="text-align:justify;">
Aligned with Hon’ble Prime Minister Narendra Modi’s vision of the Digital India where quality healthcare percolates right up to the remotest regions powered by e-Healthcare eSudha was launched in November 2024. As a cornerstone of Ayushman Bharat Scheme – world’s largest health insurance to achieve Universal Health Coverage, eSudha – is testimony to the fact that digital health has come of age in India. eSudha has digitally brought health services to the masses in rural areas and remote communities.</p>
<p style="text-align:justify;">
The cloud-based eSudha platform is implemented in two variants: 1. Provider-to-Provider telemedicine platform: this variant provides assisted teleconsultations for patients who walk into Ayushman Arogya Mandirs (earlier called Health & Wellness Centers), Community Health officers in Ayushman Arogya Mandirs facilitate the teleconsultation for the patient who are connected to the doctors and specialists in hubs established in secondary/tertiary level health facilities and medical colleges. This variant is based on a Hub-and-Spoke model. 2. Patient to Provider telemedicine platform: it empowers citizens to access health services in the confines of their homes through smartphones or laptops etc.
eSudha - National Telemedicine Service of India is providing health services remotely across the length and breadth of the country, it is offering improved access to healthcare even in resource limited settings. This marvel of ICT is bridging the digital health divide in the country. With phenomenal adoption amongst patients and telemedicine practitioners and its mammoth network extending to all parts of the country including the islands in Lakshadweep and Andamans and peaks in Ladakh, eSudha is seen as one of the crown jewels of Digital India.</p>
<p style="text-align:justify;">
Soon after COVID 19 touched Indian shores, the Telemedicine Practice Guidelines were released by the Govt. of India. eSudha was customized to be used for patient to provider tele consultations .</p>
<p style="text-align:justify;">
 eSudha has shown up as a blessing especially to people in rural areas where it was harder to access care, it has since found much wider application across the health spectrum and has revolutionized primary healthcare services in India. This first-of-its-kind, government owned telemedicine platform that has brought a colossal populace (doctors as well as patients) in the fold of the digital health ecosystem by providing free of cost consultations to one and all. It is reassuring to note that over 57% of the beneficiaries of eSudha are females and around 12% of all the beneficiaries are senior citizens. It also goes to reflect that the platform is finding its reach in the more vulnerable sections of the population where its effect is fetches maximum impact. This speaks volumes about the telemedicine platform and the extent to which it has reinvented itself over time to meet the growing demands of healthcare in India.</p>
 <p style="text-align:justify;">
Apart from the direct benefit of being able to facilitate care on demand, and leveraging the potential of information technology, eSudha successfully overcomes the challenges of geography, accessibility, cost and distance to provide equitable and quality care to populations across India. eSudha has proved to be a yardstick for swift capacity building as well as utilising digital technology to strengthen healthcare. eSudha is also shaping into the harbinger of Ayushman Bharat Digital Mission that aims to, develop the backbone necessary to support the integrated digital health infrastructure of the country. The success of this initiative is analogous with the impact and success of Digital India Mission. After tapping the potential of tele consultations to the fullest, the Ministry of Health and Family Welfare (MoHFW), Govt. of India has augmented eSudha further to add the logical next dimension of telediagnosis in eSanjeevani2.0 that was rolled out in March 2024. This entails seamless integration of a vast spectrum Point of Care Diagnostic devices (PoCDs), also known as near patient testing. PoCDs provide results of various clinical tests including physiological parameters within minutes of taking a test there by facilitating rapid diagnosis and quick decisions.</p>
<p style="text-align:justify;">
eSudha is continuously evolving to meet the dynamic needs of India's healthcare landscape. By integrating cutting-edge interventions like Artificial Intelligence (AI), it empowers both healthcare providers and patients with smarter, faster, and more personalized experiences. These advancements enhance clinical decision-making, streamline processes, and ensure a more responsive and user-friendly telemedicine service.



</p>



